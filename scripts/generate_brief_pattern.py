import random

RADIUS = 15
SIGMA = 5.0
BITS = 256
SEED = 2026

rng = random.Random(SEED)


def sample_point():
    while True:
        x = int(round(rng.gauss(0.0, SIGMA)))
        y = int(round(rng.gauss(0.0, SIGMA)))

        if -RADIUS <= x <= RADIUS and -RADIUS <= y <= RADIUS:
            return x, y


pairs = []
seen = set()

while len(pairs) < BITS:
    first = sample_point()
    second = sample_point()

    if first == second:
        continue

    # Reject both duplicate pairs and reversed pairs.
    canonical = tuple(sorted((first, second)))

    if canonical in seen:
        continue

    seen.add(canonical)
    pairs.append((*first, *second))


from pathlib import Path

# Resolve the project directory from this script's location.
project_root = Path(__file__).resolve().parent.parent
output_path = project_root / "include" / "brief_pattern.h"

lines = [
    "#ifndef PANORAMA_BRIEF_PATTERN_H",
    "#define PANORAMA_BRIEF_PATTERN_H",
    "",
    '#include "common.h"',
    "",
    "#include <array>",
    "#include <cstdint>",
    "",
    "namespace panorama {",
    "",
    "// Generated by scripts/generate_brief_pattern.py.",
    f"inline constexpr int kBriefRadius = {RADIUS};",
    "",
    "struct BriefPair {",
    "    std::int8_t dx1;",
    "    std::int8_t dy1;",
    "    std::int8_t dx2;",
    "    std::int8_t dy2;",
    "};",
    "",
    "inline constexpr std::array<BriefPair, kBriefBits> kBriefPattern{{",
]

for dx1, dy1, dx2, dy2 in pairs:
    lines.append(
        f"    {{{dx1:3d}, {dy1:3d}, {dx2:3d}, {dy2:3d}}},"
    )

lines.extend([
    "}};",
    "",
    "} // namespace panorama",
    "",
    "#endif // PANORAMA_BRIEF_PATTERN_H",
    "",
])

output_path.parent.mkdir(parents=True, exist_ok=True)
output_path.write_text("\n".join(lines), encoding="utf-8")

print(f"Saved {len(pairs)} BRIEF pairs to: {output_path}")